const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm");
const source=fs.readFileSync("internal/webui/economics.js","utf8");
assert.ok(!source.includes("\uFFFD"),"No broken Korean text");
const context=vm.createContext({Intl});
vm.runInContext(source,context);
const e=context.TraceEconomics;
const sample=(requests,input,cached,cost)=>({requests,tokens:{input,cached_input:cached,cache_write:0,cache_write_1h:0,output:10},known_usd:cost,unpriced:0});
const before=sample(10,1000,9000,1),split=sample(30,3000,12000,2);
assert.equal(e.measure(before).cache,.9);
assert.equal(e.measure(split).average,500);
const flags=e.compare(before,split).signals;
assert.ok(flags.includes("more_total_input"));
assert.ok(flags.includes("more_responses"));
assert.ok(flags.includes("quality_unknown"));
const lostCache=sample(10,7000,1000,3);
assert.ok(e.compare(before,lostCache).signals.includes("less_input_more_cost"));
assert.ok(!e.compare(before,{...lostCache,unpriced:1}).signals.includes("less_input_more_cost"));
assert.ok(e.compare(before,{...lostCache,unpriced:1}).signals.includes("price_gap"));
assert.equal(e.measure({...before,unpriced:undefined}).cost,null);
assert.equal(e.measure(sample(0,0,0,0)).cost,null);
assert.ok(e.compare(before,sample(0,0,0,0)).signals.includes("no_usage"));
assert.ok(e.compare(before,split,{beforeRating:4,afterRating:2,outcome:"good"}).signals.includes("quality_regression"));
assert.ok(e.compare(before,split,{beforeRating:4,afterRating:4,outcome:"regression"}).signals.includes("quality_regression"));
assert.ok(!e.compare(before,before,{beforeRating:4,afterRating:4,outcome:"good"}).signals.includes("quality_unknown"));
const observations=e.compare({...before,from:"2026-09-01T00:00:00Z",until:"2026-09-02T00:00:00Z",models:["a"]},{...split,from:"2026-09-02T00:00:00Z",until:"2026-09-02T01:00:00Z",models:["b"]},{incomplete:true});
for(const flag of ["different_windows","different_models","coverage_gap"])assert.ok(observations.signals.includes(flag));
assert.equal(e.agents({...before,main_responses:0,subagent_responses:0}),"—","old baseline is unknown, not zero");
assert.equal(e.agents({...before,main_responses:7,subagent_responses:3}),"7 / 3");
assert.equal(e.incomplete({sources:[{id:"codex",unresolved_usage_events:2}]}),true);
assert.equal(e.incomplete({sources:[{id:"claude",health:{missing:true}}]}),true);
assert.equal(e.incomplete({selected_source:"claude",sources:[{id:"codex",unresolved_usage_events:2},{id:"claude",health:{}}]}),false);
assert.equal(e.incomplete({health:{duplicates:4}}),false,"deduplicated snapshots are not missing data");
const spend={responses:10,usd:{input:3,cached_input:.6,cache_write:11.25,cache_write_1h:24,output:75}};
const html=e.spendHTML({...before,known_usd:113.85,spend});
for(const value of ["$3.0000","$0.6000","$35.2500","$75.0000","$113.8500","90%","not request hit rate"])assert.ok(html.includes(value),value);
const partial=e.spendHTML({...before,unpriced:1,spend:{...spend,responses:9}});
assert.ok(partial.includes("Partial amounts only"));
assert.ok(!partial.includes("$113.8500"));
const old=e.spendHTML(before,undefined,[{requests:10,unpriced:0,rates:{},usd:spend.usd}]);
assert.ok(old.includes("$35.2500"),"legacy price groups remain readable");
assert.ok(e.spendHTML({...before,spend:{responses:0,usd:{}}}).includes("unavailable"));
assert.ok(e.comparisonHTML(before,split,{language:"ko"}).includes("전체 입력은 늘었습니다"));
assert.ok(e.comparisonHTML(before,lostCache).includes("higher estimated cost"));
assert.ok(e.comparisonHTML(before,split,{beforeLabel:'<img onerror="bad">'}).includes("&lt;img"));
assert.ok(!e.comparisonHTML(before,sample(0,0,0,0)).includes("-100%"),"no observations cannot look like savings");
const graph=e.timelineHTML([before,sample(0,0,0,0),split]);
for(const text of ["25,000","21,000","40","last bucket may be partial","not occupied context"])assert.ok(graph.includes(text),text);
assert.ok(e.timelineHTML([],"ko").includes("빈 시간은 절감이 아닙니다"));
assert.ok(e.timelineHTML([before],"ko").includes("누적 사용량"));
console.log("Economics: cache costs, call multiplication, pricing gaps, quality, window/model changes, old baselines, cumulative totals and EN/KO passed.");
